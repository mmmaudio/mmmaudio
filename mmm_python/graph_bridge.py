"""Builds the audio engine and the audio graph as C dynamic libraries.

The engine (`mmm_audio/MMMAudioBridge.mojo` contains PortAudio, the Python bindings,
messaging) doesn't contain any graph, so it is compiled once per version of
`mmm_audio` and shared by every graph. 

Each audio graph is compiled on its own into a small shared C library which exposes two functions: `mmm_graph_new` and `mmm_graph_block`. The engine loads this libary at runtime (see `mmm_audio/Graph_Module.mojo`). 

If you edit an audio graph without changing the audio engine, only the audio graph needs to be compiled.

Everything that is compiled lives in `__mojocache__/`:
    - the precompiled `mmm_audio` package lives in `precompiled/`
    - the engine and graph libraries in `bridges/`.

"""

import hashlib
import importlib.util
import os
import shutil
import subprocess
from pathlib import Path

REPO_ROOT = Path(__file__).resolve().parent.parent
BRIDGE_CACHE_DIR = REPO_ROOT / "__mojocache__" / "bridges"
PRECOMPILED_DIR = REPO_ROOT / "__mojocache__" / "precompiled"

ENGINE_NAME = "MMMAudioEngine"

ENGINE_STUB = '''\
# Generated by mmm_python/graph_bridge.py - do not edit.
from std.os import abort
from std.python import PythonObject
from mmm_audio.MMMAudioBridge import make_bridge_module


@export
def PyInit_{engine_name}() abi("C") -> PythonObject:
    try:
        return make_bridge_module("{engine_name}")
    except e:
        abort(String("error creating Python Mojo module: ", e))
'''

GRAPH_STUB = '''\
# Generated by mmm_python/graph_bridge.py - do not edit.
from std.memory.alloc import unsafe_alloc
from std.origin import MutUntrackedOrigin
from mmm_audio.constants import World
from mmm_audio.Graph_Module import GraphBlock
from {package_name}.{graph_name} import {graph_name}


@export
def mmm_graph_new(world_addr: Int) abi("C") -> Int:
    try:
        var graph = unsafe_alloc[{graph_name}](1)
        graph.unsafe_write({graph_name}(World(unsafe_from_address=world_addr)))
        return Int(graph)
    except e:
        print("Error creating {graph_name}: ", e)
        return 0


@export
def mmm_graph_block(graph_addr: Int, env_addr: Int, in_addr: Int, out_addr: Int) abi("C"):
    var graph = MutPointer[{graph_name}, MutUntrackedOrigin](unsafe_from_address=graph_addr)
    var block = GraphBlock(env_addr, in_addr, out_addr)
    try:
        ref env = block.environment[]
        for i in range(block.block_size):
            block.process_single_sample(i, env)
            block.write_to_outbuf(i, graph[].next())
            block.clear_messages(i, env)
    except e:
        print("Error in {graph_name}.next: ", e)
'''

def _mojo_sources(paths):
    """Returns a collection of every .mojo file found in the project's path (files, or directories searched recursively, skipping hidden and cache directories)."""
    seen = set()

    def add(path):
        path = path.resolve()
        if path not in seen:
            seen.add(path)
            return True
        return False

    for top in map(Path, paths):
        if top.is_file():
            if add(top):
                yield top.resolve()
            continue
        for root, subdirs, files in os.walk(top):
            subdirs[:] = sorted(
                d for d in subdirs if not d.startswith(".") and d != "__mojocache__"
            )
            for f in sorted(files):
                if f.endswith(".mojo"):
                    path = Path(root, f)
                    if add(path):
                        yield path.resolve()


def source_hash(paths, extra: str = "", files=()) -> str:
    """Make a hash of any mojo files found in `extra`, every Mojo source in `paths`, and any other `files` (e.g. a .mojoc)."""
    hasher = hashlib.sha256(extra.encode("utf-8"))
    for path in [*_mojo_sources(paths), *map(Path, files)]:
        hasher.update(str(path).encode("utf-8"))
        hasher.update(path.read_bytes())
    return hasher.hexdigest()[:16]


def _run_mojo(args, source: Path):
    """Uses mojo's subprocess_run_mojo to precompile th mmm_audio.mojoc library. This will only run with the mmm_audio library changes."""
    from mojo.paths import MojoCompilationError
    from mojo.run import subprocess_run_mojo

    try:
        subprocess_run_mojo(args, capture_output=True, check=True)
    except subprocess.CalledProcessError as e:
        raise ImportError(
            str(MojoCompilationError.from_subprocess_error(source, args, e))
        ) from None


def precompile_package(source_dir, cache_dir=PRECOMPILED_DIR) -> Path:
    """Return a directory holding an up-to-date precompiled `<package>.mojoc`. This is used to compile the mmm_audio.mojoc file.
    """
    source_dir = Path(source_dir)
    name = source_dir.name
    pkg_dir = Path(cache_dir) / f"{name}-{source_hash([source_dir])}"
    if (pkg_dir / f"{name}.mojoc").is_file():
        return pkg_dir

    for old in Path(cache_dir).glob(f"{name}-*"):
        shutil.rmtree(old, ignore_errors=True)

    # Mojo names the package after the file, so it has to be `<name>.mojoc`;
    # build it in a temporary directory and move that into place, so a
    # concurrent build never sees a half-written package.
    tmp_dir = Path(cache_dir) / f"tmp-{os.getpid()}"
    tmp_dir.mkdir(parents=True, exist_ok=True)
    try:
        _run_mojo(
            ["precompile", str(source_dir), "-o", str(tmp_dir / f"{name}.mojoc")],
            source_dir,
        )
        try:
            os.rename(tmp_dir, pkg_dir)
        except OSError:
            pass  # another process got there first; its package is identical
    finally:
        shutil.rmtree(tmp_dir, ignore_errors=True)
    return pkg_dir


def build_shared_lib(
    name: str,
    stub: str,
    hash: str,
    include_dirs,
    cache_dir=BRIDGE_CACHE_DIR,
    extra_args=(),
) -> Path:
    """Uses the string format code in `stub` to create the temporary file that will be compiled to `<cache_dir>/<name>.hash-<hash>.so` (unless it's already there).

    `include_dirs` are passed as `-I` in order (Mojo takes the first match);
    `extra_args` go straight to `mojo build`, e.g. `-Xlinker` flags.
    """

    cache_dir = Path(cache_dir)
    so_path = cache_dir / f"{name}.hash-{hash}.so"
    if so_path.is_file():
        return so_path

    cache_dir.mkdir(parents=True, exist_ok=True)
    for old in cache_dir.glob(f"{name}.hash-*.so"):
        old.unlink()

    stub_path = cache_dir / f"{name}.mojo"
    stub_path.write_text(stub, encoding="utf-8")

    args = ["build", str(stub_path), "--emit", "shared-lib", "-o", str(so_path)]
    for d in dict.fromkeys(map(str, include_dirs)):
        args += ["-I", d]
    args += list(extra_args)
    _run_mojo(args, stub_path)
    return so_path

def load_extension(name: str, path):
    """Import the Python extension module `name` from the compiled library at `path`."""
    spec = importlib.util.spec_from_file_location(name, str(path))
    module = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(module)
    return module

def load_graph_bridge(graph_name: str, package_name: str):
    """This function contains code to precompile the mmm_audio package (a mojo package), build the audio engine (an .so dynamic library), and build the audio graph for `package_name.graph_name` (also a dynamic library). These will only compile if they have changed. Otherwise, previously compiled versions will be used.

    Args: 
        graph_name: The name of the audio graph to compile. Corresponds to the name of the mojo file.
        package_name: The folder where the audio graph exists.

    Returns: 
        A tuple containing `(engine_module, graph_lib_path)`.

    The graph package is resolved against the current working directory,
    `mmm_audio` against its precompiled package. The graph library is rebuilt
    whenever any `.mojo` file under the working directory or the repo root
    changes; the engine only when `mmm_audio` does.

    """
    pkg_dir = precompile_package(REPO_ROOT / "mmm_audio")

    engine_stub = ENGINE_STUB.format(engine_name=ENGINE_NAME)
    engine_path = build_shared_lib(ENGINE_NAME, engine_stub, pkg_dir.name, [pkg_dir])

    graph_path = build_graph_lib(graph_name, package_name, pkg_dir)

    return load_extension(ENGINE_NAME, engine_path), str(graph_path)


def build_graph_lib(graph_name: str, package_name: str, pkg_dir=None) -> Path:
    """Build (if needed) the shared library for `package_name.graph_name` and return its path.

    The graph package is resolved against the current working directory and the repo root.
    `pkg_dir` is the precompiled `mmm_audio` package directory (built if not given).
    """
    if pkg_dir is None:
        pkg_dir = precompile_package(REPO_ROOT / "mmm_audio")

    graph_stub = GRAPH_STUB.format(package_name=package_name, graph_name=graph_name)
    source_dirs = [Path.cwd().resolve(), REPO_ROOT]
    # The package directory must come first: Mojo takes the first match on the
    # include path, and the repo root also holds the `mmm_audio` sources.
    return build_shared_lib(
        f"{graph_name}Graph",
        graph_stub,
        source_hash(source_dirs, graph_stub),
        [pkg_dir, *source_dirs],
    )
